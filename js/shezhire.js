function showShezhireDetail(key) {
  const item = shezhireData[key];
  if (!item) return;

  const modal = document.getElementById("shezhireModal");
  const title = document.getElementById("modalNodeName");
  const tag = document.getElementById("modalNodeTag");
  const role = document.getElementById("modalNodeRole");
  const bio = document.getElementById("modalNodeBio");
  const lineage = document.getElementById("modalNodeLineage");

  title.innerText = item.name;
  tag.innerText = item.title;
  role.innerText = item.role;
  bio.innerText = item.bio;
  lineage.innerText = item.lineage;

  modal.classList.add("open");
}

function closeShezhireModal() {
  const modal = document.getElementById("shezhireModal");
  if (modal) {
    modal.classList.remove("open");
  }
}

// Global click event to close modal on background click
window.addEventListener("click", (e) => {
  const modal = document.getElementById("shezhireModal");
  if (e.target === modal) {
    closeShezhireModal();
  }
});
